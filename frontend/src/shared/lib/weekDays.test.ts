import { describe, expect, it } from 'vitest';

import { startOfWeek, weekDays } from './date';

describe('startOfWeek', () => {
  it.each([
    ['среда → понедельник той же недели', '2026-11-18', '2026-11-16'],
    ['понедельник → сам себя', '2026-11-16', '2026-11-16'],
    ['воскресенье → понедельник прошедшей недели', '2026-11-22', '2026-11-16'],
    ['через границу месяца', '2026-12-02', '2026-11-30'],
    ['через границу года', '2027-01-01', '2026-12-28'],
  ])('%s', (_name, date, monday) => {
    expect(startOfWeek(date)).toBe(monday);
  });
});

describe('weekDays', () => {
  it('семь дней с понедельника по воскресенье', () => {
    expect(weekDays('2026-11-18')).toEqual([
      '2026-11-16',
      '2026-11-17',
      '2026-11-18',
      '2026-11-19',
      '2026-11-20',
      '2026-11-21',
      '2026-11-22',
    ]);
  });
});
