import styles from './PrivacyNotice.module.css';

interface PrivacyNoticeProps {
  /**
   * `brief` — одна фраза (экран приветствия), `full` — подробно (настройки),
   * `install` — перед скачиванием приложения: данные из браузера не переносятся.
   */
  variant: 'brief' | 'full' | 'install';
}

/**
 * Что происходит с данными (решение №50) — один текст для всех экранов. Честно: на сервер
 * уходит только то, что человек отправит сам (поддержка, предложенный продукт), анонимно.
 */
export const PrivacyNotice = ({ variant }: PrivacyNoticeProps) => {
  if (variant === 'brief') {
    return (
      <p className={styles.note}>
        🔒 Ваши данные хранятся только на этом устройстве. Мы не собираем и не храним информацию о
        вас.
      </p>
    );
  }
  if (variant === 'install') {
    return (
      <p className={styles.note}>
        Приложение начнёт с чистого листа: данные из браузера в него не переносятся — профиль,
        кладовую и рецепты придётся завести заново.
      </p>
    );
  }
  return (
    <ul className={styles.list}>
      <li>Профиль, кладовая, дневник и рецепты хранятся только на этом устройстве.</li>
      <li>Мы не собираем и не храним информацию о вас: нет регистрации, имени и контактов.</li>
      <li>
        На сервер уходит только то, что вы отправите сами, — обращения в поддержку и предложенные
        продукты, анонимно.
      </li>
      <li>
        Данные не переносятся на другое устройство и между браузером и приложением. Скоро рецептом
        можно будет поделиться.
      </li>
    </ul>
  );
};
