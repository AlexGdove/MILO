import { clientIp } from './client-ip.js';

describe('IP клиента за прокси (как trust proxy в Express)', () => {
  it('без доверенных прокси — адрес соединения, X-Forwarded-For игнорируется', () => {
    expect(clientIp('172.18.0.5', '203.0.113.7', 0)).toBe('172.18.0.5');
  });

  it('один прокси (Caddy) — последний адрес из X-Forwarded-For', () => {
    expect(clientIp('172.18.0.5', '203.0.113.7', 1)).toBe('203.0.113.7');
  });

  it('подделанный клиентом X-Forwarded-For не подменяет IP: берётся адрес, добавленный прокси', () => {
    // Клиент прислал «1.1.1.1», Caddy дописал реальный адрес клиента в конец
    expect(clientIp('172.18.0.5', '1.1.1.1, 203.0.113.7', 1)).toBe('203.0.113.7');
  });

  it('два прокси — второй адрес с конца', () => {
    expect(clientIp('10.0.0.2', '203.0.113.7, 10.0.0.1', 2)).toBe('203.0.113.7');
  });

  it('цепочка короче числа прокси — самый дальний известный адрес', () => {
    expect(clientIp('172.18.0.5', '203.0.113.7', 3)).toBe('203.0.113.7');
    expect(clientIp('172.18.0.5', undefined, 1)).toBe('172.18.0.5');
  });

  it('несколько заголовков X-Forwarded-For склеиваются по порядку', () => {
    expect(clientIp('172.18.0.5', ['1.1.1.1', '203.0.113.7'], 1)).toBe('203.0.113.7');
  });

  it('пустые элементы и пробелы отбрасываются', () => {
    expect(clientIp('172.18.0.5', ' 203.0.113.7 , ,', 1)).toBe('203.0.113.7');
  });

  it('нет адреса соединения — unknown', () => {
    expect(clientIp(undefined, undefined, 0)).toBe('unknown');
  });
});
